#!/usr/bin/env python3
"""Generate engine/src/params/baseline-2026.ts from research/baseline/parameters.json.

Single source of truth stays research/baseline/parameters.json (validated against OpenFisca by
scripts/baseline_reference.py). Run: python3 -I engine/scripts/import_baseline_params.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "research", "baseline", "parameters.json")
OUT = os.path.join(ROOT, "engine", "src", "params", "baseline-2026.ts")

URL = re.compile(r"https?://[^\s;,)]+")
DOMAINS = {
    "service-public.gouv.fr": "service-public.gouv.fr",
    "legifrance.gouv.fr": "Légifrance",
    "solidarites.gouv.fr": "solidarites.gouv.fr",
    "insee.fr": "INSEE",
    "ccomptes.fr": "Cour des comptes / CPO",
}


def label_of(src: str, url: str | None) -> str:
    text = URL.sub("", src)
    text = re.sub(r"\s*;\s*;+", " ;", text)
    text = re.sub(r"\s+", " ", text).strip(" ;,")
    text = re.sub(r"\s*\b(as republished by|republished at|read through|via|at|by|see)\s*$", "", text).strip(" ;,(")
    text = text.replace(" ( ", " (").replace("()", "").strip()
    if url:
        m = re.search(r"/vosdroits/(F\d+)", url)
        if m and "service-public" in url and (not text or len(text) < 4):
            return f"service-public.gouv.fr {m.group(1)}"
    if not text and url:
        for d, lab in DOMAINS.items():
            if d in url:
                return lab
        return url.split("/")[2]
    if len(text) > 160:
        text = text[:157].rstrip() + "…"
    return text


def walk(node, path, out):
    if isinstance(node, dict) and "value" in node:
        out[path] = node
        return
    if isinstance(node, dict):
        for k, v in node.items():
            if k.startswith("_"):
                continue
            walk(v, f"{path}.{k}" if path else k, out)


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    flat = {}
    walk(data, "", flat)
    lines = [
        "// GENERATED by engine/scripts/import_baseline_params.py from research/baseline/parameters.json.",
        "// Do not edit by hand: edit the JSON (single source of truth, validated against OpenFisca) and re-run",
        "//   python3 -I engine/scripts/import_baseline_params.py",
        "import type { ParamMeta } from './types.ts';",
        "",
        f"export const BASELINE_META = {{ legislation: {json.dumps(data['_meta']['legislation'], ensure_ascii=False)}, referenceDate: {json.dumps(data['_meta']['reference_date'])} }};",
        "",
        "export const BASELINE_PARAMS = {",
    ]
    for k, p in flat.items():
        src = str(p.get("source", ""))
        urls = URL.findall(src)
        url = urls[0].rstrip(".") if urls else None
        entry = {
            "value": p["value"],
            "unit": p.get("unit", ""),
            "effective": str(p.get("effective_date", "")),
            "source": {"label": label_of(src, url), **({"url": url} if url else {})},
            "status": p.get("status", ""),
        }
        lines.append(f"  {json.dumps(k)}: {json.dumps(entry, ensure_ascii=False)},")
    lines.append("} as const satisfies Record<string, ParamMeta>;")
    lines.append("")
    lines.append("export type BaselineKey = keyof typeof BASELINE_PARAMS;")
    lines.append("")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {len(flat)} parameters to {OUT}")


if __name__ == "__main__":
    main()
